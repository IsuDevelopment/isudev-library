<?php
/**
 * Builds the generated catalog in agents/README.md: blocks, extensions and
 * every `isudev_library/*` hook with the shipped doc that explains it.
 *
 * Usage: php tools/agents-catalog.php          Rewrite agents/README.md.
 *        Required by tools/checks/320-agents-catalog.php, which fails when the
 *        committed catalog is stale or a hook is undocumented.
 *
 * Plain PHP, no WordPress. Descriptors are required with ABSPATH defined and a
 * pass-through `__()`.
 *
 * @package IsuDevLibrary
 */

declare( strict_types = 1 );

defined( 'ABSPATH' ) || define( 'ABSPATH', dirname( __DIR__ ) . '/' );

if ( ! function_exists( '__' ) ) {
	/**
	 * Shim: no translation.
	 *
	 * @param string $text Text.
	 * @return string
	 */
	function __( $text ) {
		return $text;
	}
}

const ISUDEV_CATALOG_BEGIN = '<!-- catalog:begin — generated by `php tools/agents-catalog.php`; do not edit by hand -->';
const ISUDEV_CATALOG_END   = '<!-- catalog:end -->';

/**
 * Plugin-relative paths of files below `$dir` matching `$pattern`, sorted.
 *
 * @param string $root    Plugin root with trailing slash.
 * @param string $dir     Relative directory.
 * @param string $pattern Regex on the relative path.
 * @return string[]
 */
function isudev_catalog_files( string $root, string $dir, string $pattern ): array {
	$files = array();

	if ( ! is_dir( $root . $dir ) ) {
		return $files;
	}

	$iterator = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $root . $dir, FilesystemIterator::SKIP_DOTS ) );

	foreach ( $iterator as $file ) {
		$relative = substr( $file->getPathname(), strlen( $root ) );

		if ( 1 === preg_match( $pattern, $relative ) ) {
			$files[] = $relative;
		}
	}

	sort( $files );

	return $files;
}

/**
 * Every block: name, title, description, README.
 *
 * @param string $root Plugin root.
 * @return array[]
 */
function isudev_catalog_blocks( string $root ): array {
	$blocks = array();

	foreach ( glob( $root . 'src/blocks/*/block.json' ) ?: array() as $file ) {
		$json = json_decode( (string) file_get_contents( $file ), true ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		$slug = basename( dirname( $file ) );

		$blocks[] = array(
			'name'        => (string) ( $json['name'] ?? '' ),
			'title'       => (string) ( $json['title'] ?? '' ),
			'description' => (string) ( $json['description'] ?? '' ),
			'parent'      => isset( $json['parent'] ) ? implode( ', ', (array) $json['parent'] ) : '',
			'readme'      => 'src/blocks/' . $slug . '/README.md',
		);
	}

	return $blocks;
}

/**
 * Every extension: slug, title, category, README.
 *
 * @param string $root Plugin root.
 * @return array[]
 */
function isudev_catalog_extensions( string $root ): array {
	$extensions = array();

	foreach ( glob( $root . 'extensions/*/extension.php' ) ?: array() as $file ) {
		$descriptor = require $file;

		if ( ! is_array( $descriptor ) ) {
			continue;
		}

		$slug         = basename( dirname( $file ) );
		$extensions[] = array(
			'slug'     => $slug,
			'title'    => (string) ( $descriptor['title'] ?? $slug ),
			'category' => (string) ( $descriptor['category'] ?? '' ),
			'readme'   => 'extensions/' . $slug . '/README.md',
		);
	}

	return $extensions;
}

/**
 * Hook names used in runtime code. Dynamic parts become `{name}`.
 *
 * @param string $root Plugin root.
 * @return array name => [ 'type' => 'filter'|'action'|'js filter', 'files' => string[] ]
 */
function isudev_catalog_hooks( string $root ): array {
	$hooks = array();
	$code  = array_merge(
		isudev_catalog_files( $root, 'includes', '/\.php$/' ),
		isudev_catalog_files( $root, 'src', '/\.(php|js)$/' ),
		isudev_catalog_files( $root, 'extensions', '/\.(php|js)$/' )
	);

	foreach ( $code as $relative ) {
		$source = (string) file_get_contents( $root . $relative ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents

		preg_match_all( '/\b(apply_filters|do_action|applyFilters|doAction)\(\s*([\'"])((?:isudev_library\/|isudevLibrary\.)[^\'"]+)\2/', $source, $matches, PREG_SET_ORDER );

		foreach ( $matches as $match ) {
			$name = (string) preg_replace( '/\{\$(\w+)\}|\$(\w+)/', '{$1$2}', $match[3] );
			$type = array(
				'apply_filters' => 'filter',
				'do_action'     => 'action',
				'applyFilters'  => 'JS filter',
				'doAction'      => 'JS action',
			)[ $match[1] ];

			$hooks[ $name ]['type']    = $type;
			$hooks[ $name ]['files'][] = $relative;
		}
	}

	ksort( $hooks );

	return $hooks;
}

/**
 * Shipped docs that mention a hook.
 *
 * @param string $root Plugin root.
 * @param string $name Hook name.
 * @return string[]
 */
function isudev_catalog_hook_docs( string $root, string $name ): array {
	static $docs = null;

	if ( null === $docs ) {
		$docs = array();
		foreach ( array_merge( glob( $root . 'src/blocks/*/README.md' ) ?: array(), glob( $root . 'extensions/*/README.md' ) ?: array(), glob( $root . 'guides/*.md' ) ?: array(), glob( $root . 'includes/*/README.md' ) ?: array(), array( $root . 'README.md' ) ) as $file ) {
			$docs[ substr( $file, strlen( $root ) ) ] = (string) file_get_contents( $file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		}
	}

	$found = array();

	foreach ( $docs as $relative => $text ) {
		if ( false !== strpos( $text, $name ) ) {
			$found[] = $relative;
		}
	}

	// Guides first: they hold the theme-side depth.
	usort(
		$found,
		static function ( string $a, string $b ): int {
			return ( 0 === strpos( $b, 'guides/' ) ) <=> ( 0 === strpos( $a, 'guides/' ) ) ?: strcmp( $a, $b );
		}
	);

	return $found;
}

/**
 * The generated catalog, links relative to agents/.
 *
 * @param string $root Plugin root.
 * @return array{markdown:string,undocumented:string[]}
 */
function isudev_catalog_build( string $root ): array {
	$cell  = static function ( string $text ): string {
		return str_replace( array( '|', "\n" ), array( '\\|', ' ' ), $text );
	};
	$lines = array( ISUDEV_CATALOG_BEGIN, '', '## Blocks', '', '| Block | Title | What it is | Docs |', '| --- | --- | --- | --- |' );

	foreach ( isudev_catalog_blocks( $root ) as $block ) {
		$what    = $block['description'] . ( '' !== $block['parent'] ? ' Inside ' . $block['parent'] . '.' : '' );
		$lines[] = sprintf( '| `%s` | %s | %s | [README](../%s) |', $block['name'], $cell( $block['title'] ), $cell( $what ), $block['readme'] );
	}

	array_push( $lines, '', '## Extensions', '', 'Off until enabled (admin panel or `isudev.json` → `library.extensions.{slug}.enabled`).', '', '| Slug | Title | Category | Docs |', '| --- | --- | --- | --- |' );

	foreach ( isudev_catalog_extensions( $root ) as $extension ) {
		$lines[] = sprintf( '| `%s` | %s | %s | [README](../%s) |', $extension['slug'], $cell( $extension['title'] ), $extension['category'], $extension['readme'] );
	}

	array_push( $lines, '', '## Hooks', '', 'Every hook the plugin fires, with the shipped doc that explains it and shows an example.', '', '| Hook | Type | Docs |', '| --- | --- | --- |' );

	$undocumented = array();

	foreach ( isudev_catalog_hooks( $root ) as $name => $hook ) {
		$docs = isudev_catalog_hook_docs( $root, $name );

		if ( array() === $docs ) {
			$undocumented[] = $name;
		}

		$links   = array_map(
			static function ( string $doc ): string {
				return sprintf( '[%s](../%s)', $doc, $doc );
			},
			array_slice( $docs, 0, 2 )
		);
		$lines[] = sprintf( '| `%s` | %s | %s |', $name, $hook['type'], array() === $links ? '—' : implode( ', ', $links ) );
	}

	array_push( $lines, '', '## Guides', '' );

	foreach ( glob( $root . 'guides/*.md' ) ?: array() as $file ) {
		$relative = substr( $file, strlen( $root ) );
		$first    = strtok( (string) file_get_contents( $file ), "\n" ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		$lines[]  = sprintf( '- [%s](../%s)', trim( ltrim( (string) $first, '# ' ) ), $relative );
	}

	array_push( $lines, '', ISUDEV_CATALOG_END );

	return array(
		'markdown'     => implode( "\n", $lines ),
		'undocumented' => $undocumented,
	);
}

/**
 * Put the catalog between the markers of a guide.
 *
 * @param string $guide   Current agents/README.md.
 * @param string $catalog Generated block.
 * @return string
 */
function isudev_catalog_splice( string $guide, string $catalog ): string {
	$start = strpos( $guide, ISUDEV_CATALOG_BEGIN );
	$end   = strpos( $guide, ISUDEV_CATALOG_END );

	if ( false === $start || false === $end || $end < $start ) {
		return rtrim( $guide ) . "\n\n" . $catalog . "\n";
	}

	return substr( $guide, 0, $start ) . $catalog . substr( $guide, $end + strlen( ISUDEV_CATALOG_END ) );
}

if ( PHP_SAPI === 'cli' && isset( $argv[0] ) && realpath( $argv[0] ) === __FILE__ ) {
	$isudev_root   = dirname( __DIR__ ) . '/';
	$isudev_guide  = $isudev_root . 'agents/README.md';
	$isudev_result = isudev_catalog_build( $isudev_root );

	file_put_contents( $isudev_guide, isudev_catalog_splice( (string) file_get_contents( $isudev_guide ), $isudev_result['markdown'] ) ); // phpcs:ignore WordPress.WP.AlternativeFunctions

	echo "Wrote agents/README.md\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped

	foreach ( $isudev_result['undocumented'] as $isudev_hook ) {
		fwrite( STDERR, "Undocumented hook: {$isudev_hook}\n" ); // phpcs:ignore WordPress.WP.AlternativeFunctions
	}
}
